import React, { useState, useEffect } from 'react';
import { useAuth } from '../context/AuthContext';
import { Bell, Check, Clock, ShieldCheck } from 'lucide-react';

export default function NotificationsPage() {
  const { currentUser } = useAuth();
  const [notifications, setNotifications] = useState([]);
  const [loading, setLoading] = useState(true);

  const fetchNotifs = () => {
    if (!currentUser) return;
    setLoading(true);
    fetch(`/api/notifications?userId=${currentUser.userId}`, {
      headers: { 'x-user-id': currentUser.userId }
    })
      .then(res => res.json())
      .then(data => {
        if (Array.isArray(data)) setNotifications(data);
        setLoading(false);
      })
      .catch(() => setLoading(false));
  };

  useEffect(() => {
    fetchNotifs();
  }, [currentUser]);

  const handleMarkRead = async (notifId) => {
    try {
      await fetch(`/api/notifications/${notifId}/read`, {
        method: 'PUT',
        headers: { 'x-user-id': currentUser.userId }
      });
      setNotifications(prev =>
        prev.map(n => (n.notification_id === notifId ? { ...n, read_status: true } : n))
      );
    } catch (e) {
      console.error(e);
    }
  };

  return (
    <div style={{ maxWidth: 760, margin: '0 auto' }}>
      <div className="page-header">
        <h1 className="page-title">Campus Pool Alerts</h1>
        <p className="page-subtitle">
          Real-time transactional notifications automatically generated by MySQL triggers and background cursors.
        </p>
      </div>

      {loading ? (
        <div style={{ textAlign: 'center', padding: '40px 0', color: 'var(--text-secondary)' }}>
          Loading alerts from MySQL NOTIFICATION table...
        </div>
      ) : notifications.length === 0 ? (
        <div className="card" style={{ textAlign: 'center', padding: '50px 20px', color: 'var(--text-secondary)' }}>
          <p style={{ fontWeight: 500, fontSize: 16 }}>No notifications found.</p>
          <p style={{ fontSize: 13, color: 'var(--text-muted)', marginTop: 4 }}>
            Booking requests, approvals, and departure reminders will appear here automatically.
          </p>
        </div>
      ) : (
        <div style={{ display: 'flex', flexDirection: 'column', gap: 10 }}>
          {notifications.map(n => (
            <div
              key={n.notification_id}
              className="card"
              style={{
                padding: '14px 18px',
                display: 'flex',
                justifyContent: 'space-between',
                alignItems: 'center',
                backgroundColor: n.read_status ? 'var(--bg-surface)' : 'var(--bg-muted)',
                borderColor: n.read_status ? 'var(--border-color)' : '#D0C8BC'
              }}
            >
              <div>
                <div style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 4 }}>
                  <span className="badge badge-neutral" style={{ fontSize: 10.5 }}>
                    {n.type}
                  </span>
                  {!n.read_status && (
                    <span style={{ width: 6, height: 6, borderRadius: '50%', background: 'var(--accent-primary)' }} />
                  )}
                  <span style={{ fontSize: 12, color: 'var(--text-muted)' }}>
                    {new Date(n.sent_at).toLocaleString()}
                  </span>
                </div>
                <p style={{ fontSize: 14, color: 'var(--text-primary)' }}>
                  {n.message}
                </p>
              </div>

              {!n.read_status && (
                <button
                  className="btn btn-secondary btn-sm"
                  onClick={() => handleMarkRead(n.notification_id)}
                  title="Mark as read in MySQL"
                >
                  <Check size={13} /> Mark Read
                </button>
              )}
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
